import { createBillingCharge } from "../../apps/sync/billing-charge.mjs";
import { createBillingLoops } from "../../apps/sync/billing-renewals.mjs";
import { settleInvoice } from "../../apps/sync/billing-settle.mjs";
import { testDatabaseStore } from "../../apps/sync/test-db.mjs";
import { isE2eDatabaseName, isValidRunToken } from "../../scripts/db-identifiers.mjs";
import { databaseUrlFor, testPostgresUrl } from "../../scripts/test-environment.mjs";

const name = process.env.REMO_E2E_DATABASE_NAME;
const token = process.env.REMO_E2E_RUN_ID;
if (!isE2eDatabaseName(name) || !isValidRunToken(token) || !name.endsWith(`_${token}`)) {
  throw new Error("billing fixtures require the database generated by pnpm e2e");
}
const opened = await testDatabaseStore("plan changes browser", {
  url: databaseUrlFor(testPostgresUrl(), name),
});
if (!opened) throw new Error("the browser test database is required");
const { store } = opened;
const [action, orgId, value, email] = process.argv.slice(2);

try {
  if (action === "setup") {
    const connection = await store.createConnection({
      provider: "fake", name: `Billing changes ${value}`, mode: "live", currencies: ["RUB"],
      methodGroups: ["ru_card"], priority: 1, settings: {}, webhookToken: `plan-change-${value}`,
    });
    await store.setConnectionStatus(connection.id, { from: "draft", to: "active" });
    const prices = { pro: 29_000, team: 59_000, business: 89_000 };
    const priceId = (plan, interval) => `e2e-change-${plan}-${interval}`;
    for (const [plan, amount] of Object.entries(prices)) {
      for (const interval of ["month", "year"]) {
        const id = priceId(plan, interval);
        if (await store.priceById(id)) continue;
        await store.addPrice({ id, plan, interval, currency: "RUB", amount: interval === "month" ? amount : amount * 10 });
        await store.publishPrice(id);
      }
    }
    const middle = Math.floor(Date.now() / 300_000) * 300_000;
    const halfMonth = 15 * 86_400_000;
    const start = new Date(middle - halfMonth);
    const { invoice } = await store.withTenant(orgId, async () => {
      await store.upsertBillingAccount({ orgId, email, currency: "RUB" });
      return store.createInvoice({
        orgId, currency: "RUB", subtotal: prices.pro, total: prices.pro,
        lines: [{ kind: "subscription", plan: "pro", priceId: priceId("pro", "month"), amount: prices.pro, interval: "month" }],
        periodStart: start, periodEnd: new Date(middle + halfMonth),
      });
    });
    await settleInvoice({ store, invoice });
    await store.withTenant(orgId, () => store.pool.query(
      "update subscriptions set current_period_start = $2 where org_id = $1", [orgId, start],
    ));
    process.stdout.write(JSON.stringify({ connectionId: connection.id }));
  } else if (action === "renew") {
    const boundary = new Date(Date.now() - 1000);
    await store.withTenant(orgId, () => store.pool.query(
      "update subscriptions set current_period_end = $2 where org_id = $1", [orgId, boundary],
    ));
    const outcome = await createBillingLoops({ store, charge: createBillingCharge(store) }).tick();
    process.stdout.write(JSON.stringify({ boundary, outcome }));
  } else if (action === "cleanup") {
    await store.setConnectionStatus(value, { from: "active", to: "paused" });
  } else {
    throw new Error("unknown test fixture action");
  }
} finally {
  await store.close();
}
